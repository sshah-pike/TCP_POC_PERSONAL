"""Regenerate docs/reports/S6_calibration_values.md from config/site_understanding.json (S6 step 14). Offline.

  python scripts/s06_calibration_list.py

Every CALIBRATION_PENDING entry of the config is listed with its value and note, and every entry with a named source is listed with that
source. A test (tests/unit/site/test_calibration_in_config.py) fails when a pending entry is missing from the generated file.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def entries(node, path=()):
    if isinstance(node, dict):
        if "value" in node: yield path, node
        else:
            for k, v in node.items(): yield from entries(v, path + (k,))


def main(out=None, config_path=None, sources_path=None):
    cfg = json.load(open(config_path or os.path.join(ROOT, "config", "site_understanding.json"), encoding="utf-8"))
    src = json.load(open(sources_path or os.path.join(ROOT, "config", "data_sources.json"), encoding="utf-8"))
    rows, sourced = [], []
    for p, e in entries(cfg):
        line = (f"`{'/'.join(p)}`", json.dumps(e["value"]), e.get("note", "").replace("|", "/"))
        (rows if e["source"] == "CALIBRATION_PENDING" else sourced).append((line, e["source"]))
    L = ["# S6 calibration values (step 14)", "",
         "Generated by `scripts/s06_calibration_list.py` from `config/site_understanding.json` (and `config/data_sources.json` for the source limits). Every value below is a starting",
         "value that is USED and carries the flag CALIBRATION_PENDING in the trace; none is a calibrated or regulatory number. A test",
         "(`tests/unit/site/test_calibration_in_config.py`) keeps this list current, proves every value the code reads exists in config, and",
         "proves the S6 modules contain no other number than structural ones (0, 1, 2, a half, 180 and 360 degrees, the luminance weights, the earth radius).", "",
         f"## CALIBRATION_PENDING ({len(rows)})", "", "| config path | value | what it controls |", "| --- | --- | --- |"]
    L += [f"| {a} | {b} | {c} |" for (a, b, c), _ in rows]
    q = src["sources"]["osm_overpass"]["query_limits"]
    L += ["", "Source limits (`config/data_sources.json`, CALIBRATION_PENDING): osm_overpass `timeout_s` "
          f"{src['sources']['osm_overpass']['timeout_s']}, `query_limits.max_radius_m` {q['max_radius_m']}, `max_elements` {q['max_elements']}; "
          f"osm_api `timeout_s` {src['sources']['osm_api']['timeout_s']}, `max_bytes` {src['sources']['osm_api']['max_bytes']}.", "",
          f"## With a named source ({len(sourced)})", "", "| config path | value | source |", "| --- | --- | --- |"]
    L += [f"| {a} | {b} | {s} |" for (a, b, _), s in sourced]
    path = out or os.path.join(ROOT, "docs", "reports", "S6_calibration_values.md")
    with open(path, "w", newline="\n", encoding="utf-8") as f: f.write("\n".join(L) + "\n")
    print(len(rows), len(sourced))
    return 0


if __name__ == "__main__":
    sys.exit(main())
