"""Measurement table for saved call 1 results (owner's live check), produced by the S6 measurement code, not by hand.

  python scripts/s06_measure_report.py --profile gpt-5.6-sol [--out docs/reports/S6_gpt_nine_calls_measurements.md]

Reads var/s06_call1_check/<profile>/call*.json (written by scripts/s06_call1_check.py), parses each raw response with the call 1
parser and measures it with site_model.lengths / site_model.measure. No network, no model call, nothing is changed.
"""
import argparse, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "src"), ROOT]
SAVED = os.path.join(ROOT, "var", "s06_call1_check")
INPUTS = os.path.join(ROOT, "tests", "fixtures", "site", "spike", "inputs")


def _edge_distances(marks, mpp):
    """Distance in feet from the work point to each road-edge mark, across the road axis; 'inside' when it lies between them."""
    from tcp_planner.site_model import lengths as L
    from tcp_planner.site_model.measure import _axis, _profile, _s_at
    w = next((m for m in marks if m.feature == "work_point" and m.status == "RESOLVED" and m.points), None)
    edges = [(f, m) for f in ("road_edge_left", "road_edge_right") for m in L.usable(marks, f)]
    if w is None or not edges: return None
    u = _axis([p for _, e in edges for p in e.points]); v = (-u[1], u[0]); px, py = w.points[0]
    t, s = px * u[0] + py * u[1], px * v[0] + py * v[1]
    d = [(f, s - _s_at(_profile(e.points, u, v), t)) for f, e in edges]
    inside = len(d) >= 2 and min(x for _, x in d) < 0 < max(x for _, x in d)
    return {f: round(L.px_to_ft(abs(x), mpp), 1) for f, x in d}, inside


def build(profile):
    from tcp_planner.ai.call1 import parse_call1
    from tcp_planner.contracts import FT
    from tcp_planner.site_model import lengths as L
    from tcp_planner.site_model.measure import EdgeFailure, edge_pair
    from tcp_planner.site_model.site_config import lane_width_plausible_m
    lo, hi = lane_width_plausible_m(); rows = []
    for n in range(1, 10):
        p = os.path.join(SAVED, profile, f"call{n}.json")
        if not os.path.isfile(p): continue
        r = json.load(open(p, encoding="utf-8")); site = r["site"]
        mpp = r["image"]["mpp_sent"]
        res = parse_call1(r["raw_response"], tuple(r["image"]["sent_px"])); o = res.observations
        a, b = L.usable(res.marks, "road_edge_left"), L.usable(res.marks, "road_edge_right")
        row = {"call": n, "site": site, "rep": r["rep"], "mpp": mpp, "scale_source": f"{site}.json mpp_sent, resize_scale {r['image']['resize_scale']}"}
        lanes = o["lanes_per_direction"]; row["lanes"] = (lanes.value, lanes.confidence) if lanes.status == "RESOLVED" else ("UNKNOWN", lanes.confidence)
        row["edge_marks"] = (len(a), len(b))
        tw, why = L.traveled_way_width(res.marks, mpp)
        pair = edge_pair(a[0].points, b[0].points) if len(a) == 1 and len(b) == 1 else None
        row["pair"] = pair if not isinstance(pair, EdgeFailure) else None
        row["tw"] = tw; row["tw_reason"] = why
        row["dist"] = _edge_distances(res.marks, mpp)
        sp, why_sp = L.lane_spacing(res.marks, mpp); row["spacing"] = sp; row["lane_lines"] = len(L.usable(res.marks, "lane_line"))
        total = None
        if lanes.status == "RESOLVED": total = lanes.value if o["oneway"].value else 2 * lanes.value
        row["total_lanes"] = total
        if tw is not None and total: row["per_lane_ft"] = tw.value_ft / total; row["per_lane_ok"] = lo <= tw.value_ft / total * FT <= hi
        else: row["per_lane_ft"] = None; row["per_lane_ok"] = None
        row["gate"] = L.gate_from(o)
        row["checks"] = {"two_edge_marks": len(a) == 1 and len(b) == 1, "edges_overlap": row["pair"] is not None,
                         "work_point_mark": any(m.feature == "work_point" and m.status == "RESOLVED" for m in res.marks),
                         "lane_plausible": row["per_lane_ok"]}
        rows.append(row)
    return rows


def render(profile, rows):
    from tcp_planner.site_model.site_config import lane_width_plausible_m
    lo, hi = lane_width_plausible_m()
    out = [f"# Measurements of the nine saved call 1 results ({profile})", "",
           "Generated by `scripts/s06_measure_report.py` from the saved results, using the S6 measurement code (`site_model/lengths.py`, "
           "`site_model/measure.py`). Nothing was measured by hand; no code was changed for these results.", "",
           f"Plausibility used: lane width per lane between {lo} and {hi} m (config/pipeline_config.json fusion.lane_width_plausible_m); edge marks "
           "need exactly one usable mark each (at least two points) overlapping along the road; the work point needs a resolved mark. "
           "Interval = AI-mark error (3.0 px per edge, CALIBRATION_PENDING).", "",
           "| call | site | rep | mpp sent (m/px) | lanes per dir (conf.) | traveled way ft [interval] | road bearing | work point to each edge (ft) | lane lines / spacing ft | per-lane ft (total lanes) | checks: 2 edge marks / overlap / work point / lane plausible | parking, shoulder read |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        tw = r["tw"]; twt = f"{tw.value_ft:.1f} [{tw.interval_ft.lo:.1f}, {tw.interval_ft.hi:.1f}]" if tw else f"none ({r['tw_reason']})"
        bear = f"{r['pair'].axis_bearing_deg:.0f}° ({r['pair'].side_a}/{r['pair'].side_b})" if r["pair"] else "none"
        if r["dist"]:
            d, inside = r["dist"]; dist = ", ".join(f"{k.replace('road_edge_', '')} {v}" for k, v in d.items()) + (" (inside)" if inside else " (outside)")
        else: dist = "none"
        sp = f"{r['lane_lines']} / {r['spacing'].value_ft:.1f}" if r["spacing"] else f"{r['lane_lines']} / none"
        pl = f"{r['per_lane_ft']:.1f} ({r['total_lanes']})" if r["per_lane_ft"] is not None else "none"
        c = r["checks"]; yn = lambda v: "n/a" if v is None else "yes" if v else "NO"
        chk = " / ".join(yn(c[k]) for k in ("two_edge_marks", "edges_overlap", "work_point_mark", "lane_plausible"))
        lanes = f"{r['lanes'][0]} ({r['lanes'][1]})"
        out.append(f"| {r['call']} | {r['site']} | {r['rep']} | {r['mpp']:.4f} | {lanes} | {twt} | {bear} | {dist} | {sp} | {pl} | {chk} | {r['gate']['parking_present']}, {r['gate']['shoulder_present']} |")
    out += ["", "## Scale used per site", "", "| site | mpp sent (m/px) | source |", "| --- | --- | --- |"]
    seen = {}
    for r in rows: seen.setdefault(r["site"], r)
    for s, r in seen.items(): out.append(f"| {s} | {r['mpp']:.6f} | {r['scale_source']} |")
    out += ["", "## Spread across the three repetitions of a site", "", "| site | bearing (deg) | traveled way (ft) | lanes per direction |", "| --- | --- | --- | --- |"]
    for s in seen:
        rs = [r for r in rows if r["site"] == s]
        b = ", ".join(f"{r['pair'].axis_bearing_deg:.0f}" if r["pair"] else "-" for r in rs); w = ", ".join(f"{r['tw'].value_ft:.1f}" if r["tw"] else "-" for r in rs)
        l = ", ".join(f"{r['lanes'][0]}@{r['lanes'][1]}" for r in rs); out.append(f"| {s} | {b} | {w} | {l} |")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", required=True); ap.add_argument("--out")
    a = ap.parse_args(argv)
    rows = build(a.profile)
    if not rows: print("no saved calls for", a.profile); return 1
    text = render(a.profile, rows); print(text)
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f: f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
