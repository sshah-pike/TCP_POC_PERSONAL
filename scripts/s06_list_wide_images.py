"""List the wide (zoom 17 style) map images already stored in the repo and under var/, with place, zoom and scale. Offline.

  python scripts/s06_list_wide_images.py [--out docs/reports/S6_stored_wide_images.md]

Sources: tests/fixtures/recorded/<site>/map (recorded fixtures), tests/fixtures/site/spike/inputs (the three spike images) and
var/runs/*/evidence/manifest.json (saved legacy runs; artifacts of kind 'map'). Several runs of one place are grouped.
"""
import argparse, glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _row(source, name, meta, path, extra=""):
    c = meta.get("center") or {}
    return {"source": source, "name": name, "lat": c.get("latitude", meta.get("lat")), "lon": c.get("longitude", meta.get("lon")),
            "zoom": meta.get("zoom"), "mpp": meta.get("metres_per_pixel"), "px": meta.get("width_pixels") or meta.get("width_px"),
            "provider": meta.get("provider", "AZURE_MAPS"), "path": os.path.relpath(path, ROOT).replace(os.sep, "/"), "extra": extra}


def collect(root=ROOT):
    rows = []
    for f in sorted(glob.glob(os.path.join(root, "tests", "fixtures", "recorded", "*", "map", "*.json"))):
        d = json.load(open(f, encoding="utf-8")); site = os.path.basename(os.path.dirname(os.path.dirname(f)))
        rows.append(_row("recorded fixture", site, d["meta"], f[:-5] + ".png"))
    for f in sorted(glob.glob(os.path.join(root, "tests", "fixtures", "site", "spike", "inputs", "*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        rows.append(_row("spike input", d["site"], {**d["map_meta"], "lat": d["lat"], "lon": d["lon"]}, f[:-5] + ".jpg", d.get("point", "")))
    for f in sorted(glob.glob(os.path.join(root, "var", "runs", "*", "evidence", "manifest.json"))):
        run = os.path.basename(os.path.dirname(os.path.dirname(f)))
        try: doc = json.load(open(f, encoding="utf-8")); doc = doc.get("value", doc)
        except (OSError, ValueError): continue
        kml = ""
        for rq in glob.glob(os.path.join(root, "var", "runs", run, "ui", "request*.json")):
            try:
                d = json.load(open(rq, encoding="utf-8")); d = d.get("value", d); kml = (d.get("request") or d).get("kml_filename", "") or kml
            except (OSError, ValueError): pass
        for a in doc.get("artifacts", []):
            if a.get("kind") != "map": continue
            meta = (a.get("metadata") or {}).get("meta") or {}
            if meta: rows.append(_row("legacy run", run, meta, os.path.join(os.path.dirname(f), a.get("file") or a.get("artifact_id", "map") + ".png"), kml))
    return rows


def group(rows):
    """One line per place (centre rounded to 5 decimals) and zoom, with every source that holds it."""
    g = {}
    for r in rows:
        if r["lat"] is None: continue
        g.setdefault((round(r["lat"], 4), round(r["lon"], 4), r["zoom"]), []).append(r)
    return dict(sorted(g.items()))


def render(rows):
    g = group(rows)
    out = ["# Stored wide images", "", "Generated by `scripts/s06_list_wide_images.py` (offline). One line per place and zoom.", "",
           "| centre (lat, lon) | zoom | metres per pixel | px | provider | held as | KML / note |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for (lat, lon, z), rs in g.items():
        mpp = sorted({round(r["mpp"], 4) for r in rs if r["mpp"]}); held = sorted({f"{r['source']}: {r['name']}" for r in rs})
        note = sorted({r["extra"] for r in rs if r["extra"]})
        out.append(f"| {lat}, {lon} | {z} | {', '.join(map(str, mpp))} | {rs[0]['px']} | {rs[0]['provider']} | {'; '.join(held[:4])}{' (+%d more)' % (len(held) - 4) if len(held) > 4 else ''} | {'; '.join(note)[:120]} |")
    out += ["", f"{len(g)} places, {len(rows)} stored images."]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter); ap.add_argument("--out")
    a = ap.parse_args(argv); text = render(collect()); print(text)
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f: f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
