"""Model comparison table from the saved nine-call results of two profiles (S6 step 16). Offline, deterministic, no winner is picked.

  python scripts/s06_model_comparison.py [--profiles gpt-5.6-sol claude-opus-5-5] [--out docs/reports/S6_model_comparison.md]
  python scripts/s06_model_comparison.py --versions 1 2 3 --truth site_truth_v0.csv --second-source second_source.csv --out docs/reports/S6_model_comparison.md

Reads var/s06_call1_check/<profile>/call1..9.json (written by scripts/s06_call1_check.py; prompt version N is read from var/s06_call1_check_vN, call1..9
only: calls on other sites are not read), parses each raw response with the call 1 parser (of the version asked for)
and measures it with the S6 measurement code, then checks the mark bearing against the stand-in OSM bearings of
tests/fixtures/site/bearing/marks_nine_and_nine.json (E Second St 90 degrees, Colorado 37 degrees; Granite has no stand-in and is shown
without a bearing verdict). One table per profile, then the facts side by side. It states what was measured; it does not rank the models.
--versions 1 2 3 writes the version 1 text exactly as before, then one section per further version. With --truth (and --second-source) it ends with
the scope, the files read and the wrong-and-used and width-error numbers from scripts/s06_accuracy_report.py (--proposed-width-ft gives the second
width truth to compare with the truth file's own); --date is the date written in that section (default today).
"""
import argparse, datetime, importlib.util, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(ROOT, "src"), ROOT]
SAVED = os.path.join(ROOT, "var", "s06_call1_check")
STANDIN = os.path.join(ROOT, "tests", "fixtures", "site", "bearing", "marks_nine_and_nine.json")


def saved_dir(version=1):
    """Where the results of a prompt version are: var/s06_call1_check (version 1), var/s06_call1_check_vN."""
    return SAVED if version == 1 else f"{SAVED}_v{version}"


def call_rows(profile, version=1):
    from tcp_planner.ai.call1 import parse_call1
    from tcp_planner.contracts import FT
    from tcp_planner.data_sources.osm import axis_diff_deg
    from tcp_planner.site_model import lengths as L
    from tcp_planner.site_model.bearing_check import mark_bearing
    from tcp_planner.site_model.site_config import lane_width_plausible_m, load_site_config, setting
    standin = json.load(open(STANDIN, encoding="utf-8"))["standin_way_bearing_deg"]
    tol = setting("bearing", "tolerance_deg", load_site_config())[0]
    lo, hi = lane_width_plausible_m()
    rows = []
    for n in range(1, 10):
        p = os.path.join(saved_dir(version), profile, f"call{n}.json")
        if not os.path.isfile(p): continue
        r = json.load(open(p, encoding="utf-8")); site = r["site"]; mpp = r["image"]["mpp_sent"]
        res = parse_call1(r["raw_response"], tuple(r["image"]["sent_px"]), version=version); o = res.observations
        mb, how = mark_bearing(res.marks)
        tw, _ = L.traveled_way_width(res.marks, mpp)
        lanes = o["lanes_per_direction"]
        total = (lanes.value if o["oneway"].value else 2 * lanes.value) if lanes.status == "RESOLVED" and o["oneway"].status == "RESOLVED" else None
        per_lane = tw.value_ft * FT / total if tw is not None and total else None
        verdict = "no stand-in" if site not in standin or mb is None else ("agrees" if axis_diff_deg(mb, standin[site]) <= tol else "WRONG ROAD SUSPECTED")
        rows.append({"call": n, "site": site, "rep": r["rep"], "seconds": r.get("seconds"), "in_tok": r.get("input_tokens"), "out_tok": r.get("output_tokens"),
                     "schema_valid": r.get("schema_valid"), "unknown": sum(x.status == "UNKNOWN" for x in o.values()),
                     "lanes": None if lanes.status != "RESOLVED" else (lanes.value, lanes.confidence), "oneway": o["oneway"].value, "shoulder": o["shoulder_present"].value,
                     "parking": o["parking_present"].value, "work_location": o["work_location"].value, "bearing": mb, "bearing_from": how, "verdict": verdict,
                     "tw_ft": None if tw is None else tw.value_ft, "per_lane_m": per_lane, "per_lane_ok": None if per_lane is None else lo <= per_lane <= hi,
                     "marks": len(res.marks)})
    return rows


def fmt(x, nd=1): return "-" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def render(profiles, data, version=1):
    sfx = "" if version == 1 else f" (prompt version {version})"
    out = ["# S6 model comparison (nine calls per profile, prompt version 1)", "",
           "Generated by `scripts/s06_model_comparison.py` from the saved results. It records what was measured. **No winner is picked**: it is a",
           "nine-call sample on three sites (Granite RI, E Second St MA, Colorado MA), and the comparison that matters is made on the larger site set.",
           "Bearing verdicts use the stand-in OSM bearings described in `tests/fixtures/site/bearing/marks_nine_and_nine.json` (E Second St 90 degrees,",
           "Colorado 37 degrees), not recorded OSM data.", ""] if version == 1 else [
           f"# S6 model comparison (nine calls per profile, prompt version {version})", "",
           f"Generated by `scripts/s06_model_comparison.py` from `var/s06_call1_check_v{version}` (call1.json to call9.json only; calls on other sites are not read). The same",
           "measurements and the same stand-in bearings as the version 1 section; nothing is ranked. The prompt of this version asks for more fields than version 1,",
           "so the UNKNOWN facts count is not comparable across versions.", ""]
    for p in profiles:
        out += [f"## {p}{sfx}", "", "| call | site | rep | seconds | tokens in/out | schema valid | UNKNOWN facts | lanes per dir (conf.) | oneway | shoulder | parking | work location | mark bearing | bearing vs stand-in | traveled way ft | per lane m (plausible) |",
                "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        for r in data[p]:
            lanes = "UNKNOWN" if r["lanes"] is None else f"{r['lanes'][0]} ({r['lanes'][1]})"
            pl = "-" if r["per_lane_m"] is None else f"{r['per_lane_m']:.2f} ({'yes' if r['per_lane_ok'] else 'NO'})"
            out.append(f"| {r['call']} | {r['site']} | {r['rep']} | {fmt(r['seconds'])} | {fmt(r['in_tok'])}/{fmt(r['out_tok'])} | {r['schema_valid']} | {r['unknown']} | {lanes} | {r['oneway']} | {r['shoulder']} | {r['parking']} | {r['work_location']} | {fmt(r['bearing'], 0)} | {r['verdict']} | {fmt(r['tw_ft'])} | {pl} |")
        out.append("")
    out += [f"## Side by side per site (the three repetitions){sfx}", "", "| site | profile | mark bearings | wrong-road suspected | traveled way ft | lanes per direction (conf.) | per-lane width plausible |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for site in ("granite", "second", "colorado"):
        for p in profiles:
            rs = [r for r in data[p] if r["site"] == site]
            if not rs: continue
            out.append(f"| {site} | {p} | {', '.join(fmt(r['bearing'], 0) for r in rs)} | {sum(r['verdict'] == 'WRONG ROAD SUSPECTED' for r in rs)} of {len(rs)} | "
                       f"{', '.join(fmt(r['tw_ft']) for r in rs)} | {', '.join('UNKNOWN' if r['lanes'] is None else '%s@%s' % r['lanes'] for r in rs)} | "
                       f"{sum(bool(r['per_lane_ok']) for r in rs)} of {sum(r['per_lane_ok'] is not None for r in rs)} judged |")
    out += ["", f"## Totals{sfx}", "", "| profile | calls | schema valid | wrong-road suspected | mean seconds | mean output tokens |", "| --- | --- | --- | --- | --- | --- |"]
    for p in profiles:
        rs = data[p]
        if not rs: continue
        secs = [r["seconds"] for r in rs if r["seconds"] is not None]; toks = [r["out_tok"] for r in rs if r["out_tok"] is not None]
        out.append(f"| {p} | {len(rs)} | {sum(bool(r['schema_valid']) for r in rs)} | {sum(r['verdict'] == 'WRONG ROAD SUSPECTED' for r in rs)} | "
                   f"{fmt(sum(secs) / len(secs) if secs else None)} | {fmt(sum(toks) / len(toks) if toks else None, 0)} |")
    if version == 1:
        out += ["", "What this table cannot show: accuracy against a truth (there is no truth CSV for these sites yet), the effect of prompt version 2 (not run), or",
                "how the models behave on the eight-site set. Run `scripts/s06_accuracy_report.py` on the larger set for that."]
    return "\n".join(out) + "\n"


def _accuracy():
    spec = importlib.util.spec_from_file_location("s06_accuracy_report", os.path.join(ROOT, "scripts", "s06_accuracy_report.py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m


def _results(version, profile):
    """The saved calls call1..9.json of one profile and prompt version, as the accuracy script reads them."""
    out = []
    for n in range(1, 10):
        p = os.path.join(saved_dir(version), profile, f"call{n}.json")
        if os.path.isfile(p): out.append({**json.load(open(p, encoding="utf-8")), "_file": f"call{n}.json"})
    return out


def _shown(path):
    p = os.path.abspath(path)
    return os.path.relpath(p, ROOT).replace(os.sep, "/") if p.startswith(ROOT + os.sep) else os.path.basename(p)


def facts_section(profiles, versions, truth_path, second_path, proposed_ft, date):
    """Markdown lines: scope, the files read, wrong-and-used and the E Second St width error, from scripts/s06_accuracy_report.py."""
    ACC = _accuracy()
    truth = ACC.read_truth(truth_path); second = ACC.read_second(second_path)
    cur = truth["second"]["road_width_ft"]
    new = proposed_ft if proposed_ft is not None else cur
    truth_new = {**truth, "second": {**truth["second"], "road_width_ft": new}}
    rep_cur, rep_new = {}, {}
    for v in versions:
        by = {p: _results(v, p) for p in profiles}
        rep_cur[v], rep_new[v] = ACC.score(truth, by, second), ACC.score(truth_new, by, second)
    sources = sorted({t["truth_source"] for t in truth.values() if t["truth_source"]})
    out = ["# Scope, sources and known facts", "",
           f"- **Date:** {date}. Generated by `scripts/s06_model_comparison.py` with the accuracy numbers of `scripts/s06_accuracy_report.py`; offline, no model call, nothing ranked.",
           "- **Files read** (profiles " + ", ".join(profiles) + "): " + "; ".join(f"`{_shown(saved_dir(v))}/<profile>/call1.json` to `call9.json` (prompt version {v})" for v in versions) +
           f"; `{_shown(STANDIN)}`; the truth file `{_shown(truth_path)}`" + (f"; the second source `{_shown(second_path)}`" if second_path else "") + ".",
           "- **Not read:** any other call file in those folders. The prompt version 3 calls on the five sites without a truth (granite_p28, union_p2, tenrod, lowell_mh63, lunenburg_p70) are not compared here.",
           "- **Truth:** `" + _shown(truth_path) + "` is the PROVISIONAL truth (" + "; ".join(sources) + "). It covers three sites and is not the owner's checked ground truth.",
           "- **Second source:** " + (f"`{_shown(second_path)}`, the OSM read of the recorded fixtures, stands in for OSM where the accuracy script needs a second source." if second_path else "none supplied."),
           "- **No winner is picked (D-97).** The numbers below describe what each profile did on three sites with a provisional truth; they are not a ranking.", "",
           "## Wrong and used (a value the tool would pass on that differs from the truth)", "",
           "| prompt version | profile | field | wrong and used | sites | calls |", "| --- | --- | --- | --- | --- | --- |"]
    rows = []
    for v in versions:
        for p in profiles:
            for f, d in rep_cur[v].get(p, {"fields": {}})["fields"].items():
                if d["wrong_and_used"]:
                    calls = sorted(f"{x['site']} {x['call'][:-5]}" for x in d["wrong_rows"] if x["wrong_and_used"])
                    rows.append((v, p, f, d["wrong_and_used"], ", ".join(d["wrong_and_used_sites"]), ", ".join(calls)))
    out += [f"| v{v} | {p} | {f} | {n} | {sites} | {calls} |" for v, p, f, n, sites, calls in rows] or ["| none | | | | | |"]
    out += [""] + [f"- Prompt version {v}, {p}: {n} wrong-and-used {f} value{'s' if n != 1 else ''} ({calls})." for v, p, f, n, sites, calls in rows]
    out += ["", f"## E Second St road width error (traveled way from the marks; truth {cur} ft is the current truth, {new} ft the proposed truth)", "",
            f"| prompt version | profile | call | measured ft | error vs {cur} ft (current) | error vs {new} ft (proposed) | interval holds {cur} ft | interval holds {new} ft |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    summary = []
    for v in versions:
        for p in profiles:
            if p not in rep_cur[v]: continue
            a, b = rep_cur[v][p]["width"]["rows"], rep_new[v][p]["width"]["rows"]
            pairs = [(x, y) for x, y in zip(a, b) if x["site"] == "second"]
            for x, y in pairs:
                if x["measured"] is None: out.append(f"| v{v} | {p} | {x['call'][:-5]} | none ({x['reason']}) | | | | |"); continue
                out.append(f"| v{v} | {p} | {x['call'][:-5]} | {x['measured']:.1f} | {x['error']:+.1f} | {y['error']:+.1f} | {'yes' if x['contains'] else 'NO'} | {'yes' if y['contains'] else 'NO'} |")
            ok = [(x, y) for x, y in pairs if x["measured"] is not None]
            if ok: summary.append(f"| v{v} | {p} | {len(ok)} | {sum(abs(x['error']) for x, _ in ok) / len(ok):.1f} | {sum(abs(y['error']) for _, y in ok) / len(ok):.1f} |")
    out += ["", f"| prompt version | profile | calls measured | mean absolute error vs {cur} ft | mean absolute error vs {new} ft |", "| --- | --- | --- | --- | --- |"] + summary
    out += ["", "The width interval is the AI-mark error of the measurement code (CALIBRATION_PENDING). The proposed 34 ft is the MassDOT curb-to-curb width from the research notes; it is not yet the truth file's value.",
            "The version 1 section above was written before prompt versions 2 and 3 were run: its closing sentence about version 2 (not run) is out of date."]
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profiles", nargs="+", default=["gpt-5.6-sol", "claude-opus-5-5"]); ap.add_argument("--out")
    ap.add_argument("--versions", nargs="+", type=int, choices=(1, 2, 3), default=[1], help="prompt versions to include (default: 1 only)")
    ap.add_argument("--truth", help="truth csv of scripts/s06_accuracy_report.py: adds the scope and wrong-and-used section")
    ap.add_argument("--second-source"); ap.add_argument("--proposed-width-ft", type=float); ap.add_argument("--date", default=datetime.date.today().isoformat())
    a = ap.parse_args(argv)
    data = {v: {p: call_rows(p, v) for p in a.profiles} for v in a.versions}
    if not any(rows for d in data.values() for rows in d.values()): print("no saved results found under var/s06_call1_check"); return 2
    text = "\n".join(render(a.profiles, data[v], v) for v in a.versions)
    if a.truth: text += "\n" + "\n".join(facts_section(a.profiles, a.versions, a.truth, a.second_source, a.proposed_width_ft, a.date)) + "\n"
    if a.out:
        with open(a.out, "w", encoding="utf-8", newline="\n") as f: f.write(text)
        print(f"wrote {a.out}")
    else: print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
